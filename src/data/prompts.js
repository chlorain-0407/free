export function filterPrompts(query = '', category = '全部') {
  const words = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  return PROMPTS.filter(item => (category === '全部' || item.category === category)
    && words.every(word => `${item.title} ${item.category} ${item.summary} ${item.body}`.toLocaleLowerCase().includes(word)));
}
