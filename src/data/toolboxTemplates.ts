export function extractTemplateVariables(promptBody: string): string[] {
  const regex = /\[([^\]]+)\]/g;
  const seen = new Set<string>();
  const result: string[] = [];
  let match: RegExpExecArray | null = regex.exec(promptBody);
  while (match !== null) {
    const token = match[1].trim();
    if (token && !seen.has(token)) {
      seen.add(token);
      result.push(token);
    }
    match = regex.exec(promptBody);
  }
  return result;
}

export function renderFilledPrompt(
  promptBody: string,
  values: Record<string, string>
): string {
  return promptBody.replace(/\[([^\]]+)\]/g, (_full, key: string) => {
    const trimmed = key.trim();
    const val = (values[trimmed] ?? "").trim();
    return val ? val : `[${trimmed}]`;
  });
}
